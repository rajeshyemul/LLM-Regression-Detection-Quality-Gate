import json
from pydantic import BaseModel, Field, ValidationError

from app.llm.base import LLMProvider, LLMRequest, Message


class JudgeScore(BaseModel):
    """Structured output expected from the LLM-as-a-Judge."""
    score: int = Field(..., ge=1, le=5, description="Semantic relevance score from 1 to 5")
    reason: str = Field(..., min_length=5, description="Concise rationale explaining the score")


class JudgeError(RuntimeError):
    """Raised when the judge model fails to respond or produces unparseable output."""
    def __init__(self, message: str, raw_output: str | None = None):
        super().__init__(message)
        self.raw_output = raw_output


JUDGE_SYSTEM_PROMPT = """You are an impartial, expert evaluation judge.
Your task is to evaluate the quality and semantic relevance of a candidate summary compared to a human-verified reference summary for a customer support email.

Scoring Rubric (1 to 5):
- 5 (Excellent): Completely faithful to the customer's core intent. Accurate, concise, and captures all critical details (e.g., specific error codes, dollar amounts, invoice numbers).
- 4 (Good): Accurate and captures the primary issue, but has minor verbosity or omits a non-essential detail.
- 3 (Adequate): Captures the general topic, but misses a key detail (e.g. mentions 'charge' but omits 'duplicate', or is somewhat vague).
- 2 (Poor): Focuses on secondary information while missing the core problem, or includes slight inaccuracies.
- 1 (Unacceptable/Wrong): Factually incorrect, completely misses the customer's intent, or is hallucinated.

Evaluation Guidelines:
1. Compare the Actual Summary strictly against the Expected Summary and the Customer Email.
2. Be objective and calibrated. Do not give a 5 if key specific facts (invoice numbers, error codes) are omitted.
3. Output strictly valid JSON with 'score' (integer 1-5) and 'reason' (one sentence)."""


async def evaluate_summary_relevance(
    expected_summary: str,
    actual_summary: str,
    provider: LLMProvider,
    judge_model: str = "qwen2.5:7b",
    customer_email: str | None = None,
) -> JudgeScore:
    """Evaluate candidate summary relevance using an LLM-as-a-judge.

    Args:
        expected_summary: The human-verified ideal summary from the Golden Dataset.
        actual_summary: The summary generated by the feature under test.
        provider: The LLMProvider to execute the judge evaluation.
        judge_model: Model name to use for judging (e.g. 'qwen2.5:7b' or 'qwen2.5:3b').
        customer_email: Optional original email text for context grounding.

    Returns:
        JudgeScore with integer score (1-5) and explanation reason.

    Raises:
        JudgeError: If the judge output fails schema validation.
    """
    user_prompt_parts = [
        f"Expected Summary (Ground Truth):\n{expected_summary.strip()}\n",
        f"Actual Summary (Candidate Under Test):\n{actual_summary.strip()}\n",
    ]

    if customer_email:
        user_prompt_parts.insert(0, f"Original Customer Email:\n\"\"\"\n{customer_email.strip()}\n\"\"\"\n")

    user_content = "\n".join(user_prompt_parts)

    request = LLMRequest(
        messages=[
            Message(role="system", content=JUDGE_SYSTEM_PROMPT),
            Message(role="user", content=user_content),
        ],
        model=judge_model,
        temperature=0.0,
        response_schema=JudgeScore.model_json_schema(),
    )

    response = await provider.generate(request)

    try:
        return JudgeScore.model_validate_json(response.content)
    except (ValidationError, json.JSONDecodeError) as exc:
        raise JudgeError(
            f"Failed to parse judge output into JudgeScore: {exc}",
            raw_output=response.content,
        ) from exc